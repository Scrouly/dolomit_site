				<p><span>С марта 1995 года </span>
					ВПО «Доломит» путем акционирования преобразовано в открытое акционерное общество «Доломит». В настоящее время пылевидная продукция из доломита выпускается в производственных цехах №5 и №7. Основную производственную базу составляют 11 независимых технологических линий, проектной мощностью до 440 тыс.тонн в год каждая. <br>
					Технологический процесс переработки доломита заключается в первичном и вторичном дроблении, совмещенной сушке и помоле (до фракции 0-1 мм) в мельницах самоизмельчения «Аэрофол» и молотковых мельницах, улавливание готового продукта в циклонах и электрофильтрах, транспортировка продукции в силосные склады с помощью пневмотранспорта и механического транспорта. <br>
					Для обеспечения качественного и эффективного помола требуется сушка исходного сырья, имеющего естественную влажность 6-9%, которая осуществляется горячими газами технологических топок. В качестве технологического топлива ранее использовался топочный мазут марки М 100.
