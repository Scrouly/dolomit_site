					<span>В начале 70-х годов </span>
					Началось интенсивное строительство карьера «Гралево», сырьевая база требовала значительного увеличения по объемам добычи сырья. Годовая производительность карьера была определена по первоначальному проекту 5-6 млн. тонн сырья в год. В соответствии с решениями XXV съезда КПСС, в Рубе было начато строительство 3 цеха по производству доломитовой муки. В декабре 1977 года сдано в эксплуатацию две технологические линии, а ровно через год еще три технологические линии по производству известняковой муки, общей мощностью 2200 тыс.тонн в год. <br>
